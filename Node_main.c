/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_I2C1_Init();
  MX_TIM2_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  lcd_init();
  lcd_put_cur(0, 0);
  lcd_send_string("Node Garden Init");
  HAL_Delay(1500);
  lcd_clear();

  HAL_ADC_Start(&hadc1);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);

  uint8_t rx_data[5];
  char buffer1[16];
  char buffer2[16];
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE BEGIN WHILE */
    if (HAL_I2C_Mem_Read(&hi2c1, DHT12_I2C_ADDRESS, 0x00, I2C_MEMADD_SIZE_8BIT, rx_data, 5, 100) == HAL_OK)
    {
      float humidity = rx_data[0] + (rx_data[1] / 10.0f);
      float temperature = rx_data[2] + (rx_data[3] / 10.0f);

      sprintf(buffer1, "Temp: %.1f C", temperature);
      sprintf(buffer2, "Humi: %.1f %%", humidity);

      lcd_put_cur(0, 0);
      lcd_send_string(buffer1);

      lcd_put_cur(1, 0);
      lcd_send_string(buffer2);

      char lora_buffer[50];
      int len = sprintf(lora_buffer, "Temp: %.1fC, Humi: %.1f%%\r\n", temperature, humidity);
      HAL_UART_Transmit(&huart1, (uint8_t *)lora_buffer, len, 100);
    }
    else
    {
      lcd_put_cur(0, 0);
      lcd_send_string("DHT12 Error!    ");
    }

    if (HAL_ADC_PollForConversion(&hadc1, 100) == HAL_OK)
    {
      uint32_t adc_value = HAL_ADC_GetValue(&hadc1);
      uint32_t pwm_duty = adc_value >> 4;
      __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, pwm_duty);
    }
    HAL_ADC_Start(&hadc1);

    HAL_Delay(2000);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    /* USER CODE END 3 */
  }
  /* USER CODE BEGIN 3 */
  /* USER CODE END 3 */
}

